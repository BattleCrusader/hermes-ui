#!/usr/bin/env python3
"""Audit native REST usage against the gateway's FastAPI route table.

The desktop talks to the gateway over REST for history/settings and over the
WebSocket gateway for live turns. This audit answers one narrow question:
which of the gateway's REST routes does the Qt client actually call?

It is an audit, not a parity gate: a route can be intentionally unused by the
desktop (or replaced by a gateway method), so `check_parity.py` only reports
the counts. Pass `--strict` to make gaps a non-zero exit for local triage.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKEND = Path.home() / ".hermes" / "hermes-agent"
ROUTERS = BACKEND / "hermes_cli" / "web_routers"
NATIVE_DIRS = (ROOT / "src", ROOT / "tests")
OUT_MD = ROOT / "parity" / "rest_routes.md"
OUT_JSON = ROOT / "parity" / "rest_routes.json"

ROUTE_PATTERN = re.compile(
    r"@\w+\.(get|post|put|patch|delete)\(\s*[\"']([^\"']+)", re.IGNORECASE
)
NATIVE_PATTERN = re.compile(r"\"(/api/[^\"]*)\"")


def normalize(path: str) -> str:
    """Collapse path parameters so `/x/{id}` and `/x/%1` compare equal."""
    path = path.split("?", 1)[0].split("#", 1)[0]
    path = re.sub(r"%[0-9]+", "{}", path)
    path = re.sub(r"\{[^}/]+\}", "{}", path)
    path = re.sub(r"\$\{[^}/]+\}", "{}", path)
    # `%2` is often a query string built by `.arg(...)`; it is not a path
    # segment, so drop the trailing parameter when it is not `/`-prefixed.
    path = re.sub(r"(?<!/)\{\}$", "", path)
    path = re.sub(r"/+$", "", path)
    return path or "/"


def backend_routes() -> list[dict[str, str]]:
    routes: dict[tuple[str, str], str] = {}
    if not ROUTERS.exists():
        return []
    for source in sorted(ROUTERS.glob("*.py")):
        text = source.read_text(encoding="utf-8", errors="replace")
        for verb, path in ROUTE_PATTERN.findall(text):
            method = verb.upper()
            routes[(method, normalize(path))] = path
    return [
        {
            "method": method,
            "path": path,
            "normalized": normalized,
            "source": "hermes_cli/web_routers",
        }
        for (method, normalized), path in sorted(routes.items())
    ]


def _plausible_path(raw: str) -> bool:
    """Reject prose strings that merely start with `/api`."""
    return not re.search(r"[\s;<>\"']", raw) and "//" not in raw


def native_routes() -> list[dict[str, str]]:
    found: dict[str, str] = {}
    for directory in NATIVE_DIRS:
        if not directory.exists():
            continue
        for source in sorted(directory.rglob("*")):
            if source.suffix not in {".cc", ".h"}:
                continue
            text = source.read_text(encoding="utf-8", errors="replace")
            for match in NATIVE_PATTERN.finditer(text):
                raw = match.group(1)
                if not _plausible_path(raw):
                    continue
                found.setdefault(normalize(raw), str(source.relative_to(ROOT)))
    return [
        {"path": normalized, "source": where}
        for normalized, where in sorted(found.items())
    ]


def audit() -> dict:
    backend = backend_routes()
    native = native_routes()
    native_paths = {route["path"] for route in native}
    backend_paths = {route["normalized"] for route in backend}

    rows = []
    matched = 0
    for route in backend:
        used = route["normalized"] in native_paths
        matched += int(used)
        rows.append(
            {
                "method": route["method"],
                "path": route["path"],
                "normalized": route["normalized"],
                "native": used,
            }
        )
    extra = [
        route
        for route in native
        if route["path"] not in backend_paths and route["source"].startswith("src/")
    ]
    test_references = sum(
        1 for route in native if route["source"].startswith("tests/")
    )
    return {
        "summary": {
            "backend_routes": len(backend),
            "native_routes": len(native),
            "matched": matched,
            "gaps": len(backend) - matched,
            "native_only": len(extra),
            "test_references": test_references,
        },
        "routes": rows,
        "native_only": extra,
    }


def write_report(result: dict) -> None:
    summary = result["summary"]
    lines = [
        "# Gateway REST route audit",
        "",
        "Generated by `parity/rest_routes.py` from "
        "`~/.hermes/hermes-agent/hermes_cli/web_routers` and the `/api/...` "
        "literals in `src/` + `tests/`.",
        "",
        f"- Backend routes: **{summary['backend_routes']}**",
        f"- Native `/api` paths: **{summary['native_routes']}**",
        f"- Backend paths seen in the native client: **{summary['matched']}**",
        f"- Native-only paths (fragments, desktop-only calls): "
        f"**{summary['native_only']}**",
        f"- Test fixture `/api` literals seen: **{summary['test_references']}** "
        "(ignored unless they match a gateway route)",
        "",
        "Matching is path-level (HTTP verb is not inferred from C++ call "
        "sites). Query strings and `{id}` / `%1` parameters are normalized.",
        "",
        "| Method | Gateway route | Native |",
        "| --- | --- | --- |",
    ]
    for row in result["routes"]:
        lines.append(
            f"| {row['method']} | `{row['path']}` | "
            f"{'yes' if row['native'] else 'gap'} |"
        )
    if result["native_only"]:
        lines += ["", "## Native-only `/api` paths", ""]
        for row in result["native_only"]:
            lines.append(f"- `{row['path']}` — `{row['source']}`")
    lines.append("")
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    OUT_JSON.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--strict",
        action="store_true",
        help="exit non-zero when backend routes are unused by the native client",
    )
    args = parser.parse_args()
    result = audit()
    write_report(result)
    summary = result["summary"]
    print(
        "REST routes: "
        f"{summary['matched']}/{summary['backend_routes']} matched, "
        f"{summary['gaps']} gaps, {summary['native_only']} native-only"
    )
    if args.strict and summary["gaps"]:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
