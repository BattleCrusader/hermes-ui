#!/usr/bin/env python3
"""Generate src/theme_presets.{h,cc} from resources/themes/*.json.

The JSON files are the colour schemes of https://github.com/beatreichenbach/qt-themes
(MIT, (c) 2024 Beat Reichenbach). Each file names 20 palette roles; the Hermes
theme has finer-grained tokens, so the mapping below derives them:

    background      <- base            surface        <- surface0
    sidebar         <- crust           surface_raised <- surface1
    foreground      <- text            text_secondary <- subtext0
    text_tertiary   <- overlay0        stroke         <- surface1
    stroke_strong   <- surface2        accent         <- primary
    user_bubble     <- mix(base, primary, 0.18)
    success/warning/danger <- green/yellow/red

Run: python3 scripts/gen_theme_presets.py
Never hand-edit src/theme_presets.cc.
"""

import json
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
THEMES_DIR = ROOT / "resources" / "themes"

TITLES = {
    "atom_one": "Atom One",
    "blender": "Blender",
    "catppuccin_frappe": "Catppuccin Frapp\u00e9",
    "catppuccin_latte": "Catppuccin Latte",
    "catppuccin_macchiato": "Catppuccin Macchiato",
    "catppuccin_mocha": "Catppuccin Mocha",
    "dracula": "Dracula",
    "github_dark": "GitHub Dark",
    "github_light": "GitHub Light",
    "modern_dark": "Modern Dark",
    "modern_light": "Modern Light",
    "monokai": "Monokai",
    "nord": "Nord",
    "one_dark_two": "One Dark Two",
}

# Hermes' own look is a near-black neutral surface with a blue accent;
# GitHub Dark is the closest preset of the set, so it leads the gallery.
ORDER = [
    "github_dark",
    "one_dark_two",
    "modern_dark",
    "atom_one",
    "monokai",
    "dracula",
    "nord",
    "catppuccin_mocha",
    "catppuccin_macchiato",
    "catppuccin_frappe",
    "blender",
    "github_light",
    "catppuccin_latte",
    "modern_light",
]


def luminance(hex_color):
    raw = hex_color.lstrip("#")
    return (
        int(raw[0:2], 16) * 0.299
        + int(raw[2:4], 16) * 0.587
        + int(raw[4:6], 16) * 0.114
    )


def load(theme_id):
    with open(THEMES_DIR / f"{theme_id}.json", encoding="utf-8") as handle:
        return json.load(handle)


def group_of(palette):
    """Light or dark, from the luminance of base vs text."""
    return "dark" if luminance(palette["text"]) > luminance(palette["base"]) else "light"


def entry(theme_id):
    p = load(theme_id)
    return (
        "    {\n"
        f'        "{theme_id}",\n'
        f'        "{TITLES[theme_id]}",\n'
        f'        "{group_of(p)}",\n'
        "        Build(\n"
        f'            "{p["base"]}", "{p["crust"]}", "{p["surface0"]}",\n'
        f'            "{p["surface1"]}", "{p["text"]}", "{p["subtext0"]}",\n'
        f'            "{p["overlay0"]}", "{p["surface1"]}", "{p["surface2"]}",\n'
        f'            "{p["primary"]}", "{p["secondary"]}", "{p["surface0"]}",\n'
        f'            "{p["surface1"]}", "{p["text"]}", "{p["green"]}",\n'
        f'            "{p["yellow"]}", "{p["red"]}", "{p["cyan"]}",\n'
        f'            "{p["magenta"]}", "{p["blue"]}"),\n'
        "    },\n"
    )


HEADER = '''// Copyright 2026 The Hermes Qt Spike Authors.
// Generated by scripts/gen_theme_presets.py - do not edit by hand.

#ifndef HERMES_UI_THEME_PRESETS_H_
#define HERMES_UI_THEME_PRESETS_H_

#include <QString>
#include <vector>

#include "src/theme.h"

namespace hermes::ui {

// One selectable colour scheme. `group` is "dark" or "light" for the
// gallery's column layout.
struct ThemePreset {
  QString id;
  QString name;
  QString group;
  Theme theme;
};

std::vector<ThemePreset> ThemePresets();

// Empty id, or an unknown id, returns a default-constructed preset (empty
// id and name) - callers keep the current theme in that case.
ThemePreset ThemePresetById(const QString& id);

}  // namespace hermes::ui

#endif  // HERMES_UI_THEME_PRESETS_H_
'''

BODY_HEAD = '''// Copyright 2026 The Hermes Qt Spike Authors.
// Generated by scripts/gen_theme_presets.py - do not edit by hand.
// Colour schemes from https://github.com/beatreichenbach/qt-themes (MIT).

#include "src/theme_presets.h"

#include <vector>

#include <QColor>

namespace hermes::ui {
namespace {

// Accent tints keep the desktop's translucency: 46% for accent fills, 56% for
// a selected row, 16% for hover, 18% of accent in the user bubble.
QColor Alpha(const char* hex, int alpha) {
  QColor color(QString::fromLatin1(hex));
  color.setAlpha(alpha);
  return color;
}

QColor MixColors(const QColor& first, const QColor& second, double amount) {
  return QColor::fromRgbF(
      first.redF() + (second.redF() - first.redF()) * amount,
      first.greenF() + (second.greenF() - first.greenF()) * amount,
      first.blueF() + (second.blueF() - first.blueF()) * amount);
}

Theme Build(const char* background, const char* sidebar, const char* surface,
            const char* surface_raised, const char* foreground,
            const char* text_secondary, const char* text_tertiary,
            const char* stroke, const char* stroke_strong, const char* accent,
            const char* accent_text, const char* code_background,
            const char* code_header, const char* code_text, const char* success,
            const char* warning, const char* danger, const char* code_string,
            const char* code_keyword, const char* code_number) {
  Theme theme = Theme::Dark();
  theme.background = QColor(QString::fromLatin1(background));
  theme.sidebar = QColor(QString::fromLatin1(sidebar));
  theme.surface = QColor(QString::fromLatin1(surface));
  theme.surface_raised = QColor(QString::fromLatin1(surface_raised));
  theme.foreground = QColor(QString::fromLatin1(foreground));
  theme.text_secondary = QColor(QString::fromLatin1(text_secondary));
  theme.text_tertiary = QColor(QString::fromLatin1(text_tertiary));
  theme.stroke = QColor(QString::fromLatin1(stroke));
  theme.stroke_strong = QColor(QString::fromLatin1(stroke_strong));
  theme.accent = QColor(QString::fromLatin1(accent));
  theme.accent_soft = Alpha(accent, 46);
  theme.accent_text = QColor(QString::fromLatin1(accent_text));
  theme.selected = Alpha(accent, 56);
  theme.hover = Alpha(foreground, 16);
  theme.user_bubble = MixColors(theme.background, theme.accent, 0.18);
  theme.code_background = QColor(QString::fromLatin1(code_background));
  theme.code_header = QColor(QString::fromLatin1(code_header));
  theme.code_text = QColor(QString::fromLatin1(code_text));
  theme.code_comment = QColor(QString::fromLatin1(text_tertiary));
  theme.code_keyword = QColor(QString::fromLatin1(code_keyword));
  theme.code_string = QColor(QString::fromLatin1(code_string));
  theme.code_number = QColor(QString::fromLatin1(code_number));
  theme.success = QColor(QString::fromLatin1(success));
  theme.warning = QColor(QString::fromLatin1(warning));
  theme.danger = QColor(QString::fromLatin1(danger));
  EnsureCodeContrast(&theme);
  return theme;
}

}  // namespace

std::vector<ThemePreset> ThemePresets() {
  return {
'''

BODY_TAIL = '''  };
}

ThemePreset ThemePresetById(const QString& id) {
  for (const ThemePreset& preset : ThemePresets()) {
    if (preset.id == id) {
      return preset;
    }
  }
  return {};
}

}  // namespace hermes::ui
'''


def main():
    source = BODY_HEAD + "".join(entry(t) for t in ORDER) + BODY_TAIL
    cc = ROOT / "src" / "theme_presets.cc"
    (ROOT / "src" / "theme_presets.h").write_text(HEADER, encoding="utf-8")
    cc.write_text(source, encoding="utf-8")
    # The repo lints with clang-format -style=Google; format here so generated
    # output is byte-identical to what the check expects.
    clang_format = shutil.which("clang-format")
    if clang_format:
        subprocess.run([clang_format, "-i", "-style=Google", str(cc)], check=True)
    else:
        print("clang-format not found; run it on src/theme_presets.cc", file=sys.stderr)
    print(f"wrote {len(ORDER)} presets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
